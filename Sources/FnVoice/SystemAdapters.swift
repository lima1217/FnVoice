@MainActor final class SystemPasteboard: PasteboardAccess {
    private let pb = NSPasteboard.general

    var changeCount: Int { pb.changeCount }

    func snapshot() -> [PasteboardItemSnapshot] {
        (pb.pasteboardItems ?? []).map { item in
            PasteboardItemSnapshot(entries: item.types.compactMap { type in
                item.data(forType: type).map { PasteboardEntry(type: type.rawValue, data: $0) }
            })
        }
    }

    func restore(_ items: [PasteboardItemSnapshot]) {
        pb.clearContents()
        let objects = items.filter { !$0.entries.isEmpty }.map { snap -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for e in snap.entries { item.setData(e.data, forType: NSPasteboard.PasteboardType(e.type)) }
            return item
        }
        if !objects.isEmpty { pb.writeObjects(objects) }
    }

    func writeTransient(_ text: String) -> Int {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // http://nspasteboard.org — clipboard managers skip items carrying these markers.
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
        }
        pb.writeObjects([item])
        return pb.changeCount
    }

    func writePlain(_ text: String) {
        pb.clearContents()
        pb.setString(text, forType: .string)
    }
}

@MainActor final class TISInputSources: InputSourceControl {
    func current() -> InputSourceInfo? {
        guard let src = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue() else { return nil }
        return Self.info(src)
    }

    func available() -> [InputSourceInfo] {
        Self.sources().compactMap(Self.info)
    }

    func select(id: String) -> Bool {
        guard let src = Self.sources().first(where: { Self.string(src: $0, kTISPropertyInputSourceID) == id }) else { return false }
        return TISSelectInputSource(src) == noErr
    }

    private static func sources() -> [TISInputSource] {
        let filter = [kTISPropertyInputSourceCategory as String: kTISCategoryKeyboardInputSource as String] as CFDictionary
        return (TISCreateInputSourceList(filter, false)?.takeRetainedValue() as? [TISInputSource]) ?? []
    }

    private static func property(_ src: TISInputSource, _ key: CFString) -> AnyObject? {
        guard let p = TISGetInputSourceProperty(src, key) else { return nil }
        return Unmanaged<AnyObject>.fromOpaque(p).takeUnretainedValue()
    }

    private static func string(src: TISInputSource, _ key: CFString) -> String? {
        property(src, key) as? String
    }

    private static func bool(src: TISInputSource, _ key: CFString) -> Bool {
        guard let v = property(src, key) else { return false }
        return CFBooleanGetValue((v as! CFBoolean))
    }

    private static func info(_ src: TISInputSource) -> InputSourceInfo? {
        guard let id = string(src: src, kTISPropertyInputSourceID) else { return nil }
        let type = string(src: src, kTISPropertyInputSourceType)
        return InputSourceInfo(
            id: id,
            isKeyboardLayout: type == (kTISTypeKeyboardLayout as String),
            languages: (property(src, kTISPropertyInputSourceLanguages) as? [String]) ?? [],
            isASCIICapable: bool(src: src, kTISPropertyInputSourceIsASCIICapable),
            isSelectable: bool(src: src, kTISPropertyInputSourceIsSelectCapable)
        )
    }
}

@MainActor final class CGKeystrokePoster: KeystrokePoster {
    func postPaste() {
        // Resolve "v" in the active layout: on Dvorak, the QWERTY V key position is "."
        let vKey = Self.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        let source = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    static func keyCode(for character: Character) -> CGKeyCode? {
        guard let src = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let ptr = TISGetInputSourceProperty(src, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        return data.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeys, 4, &length, &chars)
                if status == noErr, length == 1, Character(UnicodeScalar(chars[0]) ?? " ") == character {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }
}

